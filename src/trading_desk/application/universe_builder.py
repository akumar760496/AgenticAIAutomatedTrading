"""Turns a liquidity ranking into config/universe.yaml, with a diff.

The generated file keeps the same `indices` / `stocks` / `version` / `source` keys
as the hand-written starter list, so the snapshotter reads either one without
knowing which. That is the whole point of step 1.2: swap the source of truth from
memory to measurement without changing the consumer.

Three things go into the file that are not strictly needed to run, and are there
because a universe nobody can audit gets trusted for the wrong reasons:

- `measurements`, so every included name shows the numbers that got it in.
- `exclusions`, so a missing name has a stated reason rather than an absence.
- `window_days`, so a one-day point measurement is never mistaken for the 20-day
  average the build plan eventually wants.
- `measured_on`, the trading date whose session the figures describe. It comes
  from the trading calendar, not from the feed: Dhan's own `exchange_time` is the
  time it answered the request, so a Saturday survey of Friday's volume reports a
  Saturday timestamp. Without this field a universe built on stale figures is
  indistinguishable from one built live.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Any

import yaml

from trading_desk.application.exchange_rules import ExchangeRules
from trading_desk.domain.liquidity import LiquidityRanking

DEFAULT_GENERATED_PATH = Path("config/universe.yaml")

HEADER = """# Generated by the step 1.2 liquidity survey. Do not hand-edit.
#
# Regenerate with:  uv run trading-desk survey
#
# Every included name carries the measurement that got it in, and every excluded
# name carries the reason it was dropped. If a name you expect is missing, look in
# `exclusions` before changing a threshold in config/exchange_rules.yaml.
"""


@dataclass(frozen=True)
class UniverseDiff:
    """What changed against the previous universe.

    Differences against the hand-written starter list are expected and wanted - if
    a survey exactly reproduces a guess, the ranking probably is not running.
    """

    added: tuple[str, ...]
    removed: tuple[str, ...]
    kept: tuple[str, ...]

    @property
    def changed(self) -> bool:
        return bool(self.added or self.removed)

    def summary(self) -> str:
        if not self.changed:
            return f"No change: {len(self.kept)} symbols, identical to the previous universe"
        return (
            f"{len(self.kept)} kept, {len(self.added)} added, {len(self.removed)} removed\n"
            f"  added:   {', '.join(self.added) or '-'}\n"
            f"  removed: {', '.join(self.removed) or '-'}"
        )


def diff_universe(previous: tuple[str, ...], current: tuple[str, ...]) -> UniverseDiff:
    """Compare two symbol lists. Sorted output, so two runs produce one diff."""
    before, after = set(previous), set(current)
    return UniverseDiff(
        added=tuple(sorted(after - before)),
        removed=tuple(sorted(before - after)),
        kept=tuple(sorted(after & before)),
    )


def render_universe(
    *,
    ranking: LiquidityRanking,
    rules: ExchangeRules,
    as_of: date,
    version: int,
    window_days: int,
    measured_on: date,
) -> str:
    """Render the YAML document. Pure: takes the date and version, reads no clock."""
    measurements: dict[str, Any] = {}
    for measure in ranking.included:
        measurements[measure.symbol] = {
            # str(Decimal) rather than float: a turnover figure read back as a
            # float is a money value that has quietly stopped being exact.
            "premium_turnover_rupees": str(measure.premium_turnover.rupees()),
            "open_interest": measure.open_interest,
            "priced_fraction": round(measure.priced_fraction, 3),
            "legs": measure.legs_total,
        }

    body = {
        "version": version,
        "source": "step 1.2 liquidity survey",
        "effective_from": as_of,
        "window_days": window_days,
        "measured_on": measured_on,
        "rules_effective_from": rules.effective_from,
        "rules_verified": rules.verified,
        "indices": [m.symbol for m in ranking.included if m.is_index],
        "stocks": [m.symbol for m in ranking.included if not m.is_index],
        "measurements": measurements,
        "exclusions": [{"symbol": item.symbol, "reason": item.reason} for item in ranking.excluded],
    }

    return HEADER + yaml.safe_dump(body, sort_keys=False, default_flow_style=False, width=100)


def previous_symbols(path: Path) -> tuple[str, ...]:
    """Symbols in an existing universe file, or empty if there is none yet."""
    if not path.is_file():
        return ()
    raw = yaml.safe_load(path.read_text()) or {}
    return tuple(sorted(list(raw.get("indices", [])) + list(raw.get("stocks", []))))


def previous_version(path: Path) -> int:
    if not path.is_file():
        return 0
    raw = yaml.safe_load(path.read_text()) or {}
    return int(raw.get("version", 0))
